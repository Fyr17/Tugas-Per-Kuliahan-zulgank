import itertools
from pyparsing import Word, alphas, ParserElement, infixNotation, opAssoc

# 1. Definisi Grammar / Parser
ParserElement.enablePackrat()
variable = Word(alphas.lower(), max=1)

# Operator precedences
expr = infixNotation(variable, [
    ("NOT", 1, opAssoc.RIGHT, lambda t: ("NOT", t[0][1])),
    ("AND", 2, opAssoc.LEFT, lambda t: ("AND", t[0][0], t[0][2])),
    ("OR",  2, opAssoc.LEFT, lambda t: ("OR",  t[0][0], t[0][2])),
])

# 2. Fungsi Evaluasi AST
def evaluate(ast, env):
    if isinstance(ast, str):
        return env[ast]
    op = ast[0]
    if op == "NOT":
        return not evaluate(ast[1], env)
    elif op == "AND":
        return evaluate(ast[1], env) and evaluate(ast[2], env)
    elif op == "OR":
        return evaluate(ast[1], env) or evaluate(ast[2], env)

# 3. Ekstraksi Variabel & Pembangkitan Tabel
def generate_truth_table(expression_str):
    ast = expr.parseString(expression_str, parseAll=True)[0]

    # Deteksi variabel unik secara otomatis
    vars_found = sorted(list(set(c for c in expression_str if c.isalpha() and c.islower())))
    n = len(vars_found)

    print(f"\nEkspresi: {expression_str}")
    header = " | ".join(vars_found) + " | Hasil"
    print("-" * len(header))
    print(header)
    print("-" * len(header))

    # Kombinasi 2^n
    for combination in itertools.product([True, False], repeat=n):
        env = dict(zip(vars_found, combination))
        res = evaluate(ast, env)

        row_str = " | ".join(["T" if env[v] else "F" for v in vars_found])
        res_str = "T" if res else "F"
        print(f"{row_str} |   {res_str}")

# Pengujian dengan 2 ekspresi
generate_truth_table("p AND (q OR NOT r)")
generate_truth_table("(p OR q) AND NOT p")